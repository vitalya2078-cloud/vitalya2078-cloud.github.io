insert into physics.curriculum_units (
  education_level_id, topic_id, source_row_code, title, planned_hours,
  program_content_summary, learning_activity_summary, practical_work,
  source_title, source_url, source_version, source_page_start, source_page_end,
  sort_order, unit_type
