insert into physics.curriculum_units (
  education_level_id, topic_id, source_row_code, title, planned_hours,
  program_content_summary, learning_activity_summary, practical_work,
  source_title, source_url, source_version, source_page_start, source_page_end,
  sort_order, unit_type
)
select
  l.id,
  t.id,
  r.row_code,
  r.title,
  r.hours,
  r.content_summary,
  r.activity_summary,
  r.practical_work,
  case when r.program_code='school-physics-ooo-basic'
    then 'Федеральная рабочая программа по физике, 7–9 классы, базовый уровень'
    else 'Федеральная рабочая программа по физике, 7–9 классы, углублённый уровень' end,
  case when r.program_code='school-physics-ooo-basic'
    then 'https://edsoo.ru/wp-content/uploads/2025/07/2025_ooo_frp_fizika-7-9_baz.pdf'
    else 'https://edsoo.ru/wp-content/uploads/2025/07/2025_ooo_frp_fizika_7-9_ugl.pdf' end,
  '2025',
  r.page_start,
  r.page_end,
  r.sort_order,
  r.unit_type
from rows r
join physics.education_programs p on p.code=r.program_code
join physics.program_versions v on v.program_id=p.id and v.version_code='2025'
join physics.education_levels l on l.program_version_id=v.id and l.code=r.level_code
left join physics.topics t on t.slug=r.topic_slug
  and t.section_id in (select s.id from physics.sections s where s.level_id=l.id)
on conflict (education_level_id, source_row_code) do update set
  topic_id=excluded.topic_id,
  title=excluded.title,
  planned_hours=excluded.planned_hours,
  program_content_summary=excluded.program_content_summary,
  learning_activity_summary=excluded.learning_activity_summary,
  practical_work=excluded.practical_work,
  source_title=excluded.source_title,
  source_url=excluded.source_url,
  source_version=excluded.source_version,
  source_page_start=excluded.source_page_start,
  source_page_end=excluded.source_page_end,
  sort_order=excluded.sort_order,
  unit_type=excluded.unit_type,
  updated_at=now();
