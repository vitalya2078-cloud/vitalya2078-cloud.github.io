# Тексты программы для Windows: обращение на «Вы» и дефис вместо длинного тире.
# Исходники лабораторных общие с сайтом, Android и iPhone — их не меняем; преобразование делается при сборке
# только Windows-версии (build.py) и для конспектов (notes.json). Банк вопросов (bank.json) не трогается.
